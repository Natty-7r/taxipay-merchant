import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:flutter_test/flutter_test.dart';
import 'package:pointycastle/export.dart' show ECDomainParameters, ECPrivateKey;
import 'package:taxipay_merchant/core/network/secure_channel.dart';

Uint8List hex(String s) => Uint8List.fromList([for (var i = 0; i < s.length; i += 2) int.parse(s.substring(i, i + 2), radix: 16)]);

void main() {
  test('HKDF-SHA256 matches RFC 5869 test case 1', () {
    final okm = SecureCrypto.hkdf(hex('0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b'), hex('000102030405060708090a0b0c'),
        hex('f0f1f2f3f4f5f6f7f8f9'), 42);
    expect(okm, hex('3cb25f25faacd57a90434f64d0362f2a2d2d0a90cf1a5a4c5db02d56ecc4c5bf34007208d5b887185865'));
  });

  test('ECDH agrees both ways and AES-GCM detects tampering', () {
    final a = SecureCrypto.newKeyPair();
    final b = SecureCrypto.newKeyPair();
    final ab = SecureCrypto.ecdh(a.privateKey, SecureCrypto.fromRawPoint(SecureCrypto.rawPoint(b.publicKey)));
    final ba = SecureCrypto.ecdh(b.privateKey, a.publicKey);
    expect(ab, ba);
    expect(ab.length, 32);

    final iv = SecureCrypto.randomBytes(12);
    final aad = SecureCrypto.requestAad('post', '/api/x', 1, 's');
    final ct = SecureCrypto.seal(ab, iv, Uint8List.fromList(utf8.encode('{"a":1}')), aad);
    expect(utf8.decode(SecureCrypto.open(ab, iv, ct, aad)), '{"a":1}');
    expect(() => SecureCrypto.open(ab, iv, ct, SecureCrypto.requestAad('POST', '/api/y', 1, 's')), throwsA(anything));
  });

  test('rejects points that are not on the curve', () {
    expect(() => SecureCrypto.fromRawPoint(Uint8List(65)..[0] = 4), throwsA(anything));
  });

  // Generated by the API's SecureCrypto (Java) with throwaway keys: proves both sides agree byte for byte.
  test('interoperates with the Java implementation', () {
    final v = jsonDecode(File('test/core/secure_channel_vector.json').readAsStringSync()) as Map<String, dynamic>;
    Uint8List b(String k) => base64Decode(v[k] as String);
    final sid = v['sessionId'] as String;

    expect(SecureCrypto.verify(SecureCrypto.fromRawPoint(b('serverKey')),
        SecureCrypto.transcript(b('clientPub'), b('serverPub'), b('clientNonce'), b('serverNonce'), sid), b('signature')), isTrue);
    expect(SecureCrypto.verify(SecureCrypto.fromRawPoint(b('serverKey')),
        SecureCrypto.transcript(b('clientPub'), b('serverPub'), b('clientNonce'), b('serverNonce'), 'other'), b('signature')), isFalse);

    final d = b('clientPriv').fold(BigInt.zero, (acc, x) => (acc << 8) | BigInt.from(x));
    final keys = SecureCrypto.hkdf(
        SecureCrypto.ecdh(ECPrivateKey(d, ECDomainParameters('secp256r1')), SecureCrypto.fromRawPoint(b('serverPub'))),
        Uint8List.fromList([...b('clientNonce'), ...b('serverNonce')]),
        Uint8List.fromList(utf8.encode('${SecureCrypto.version} keys$sid')), 64);
    expect(keys.sublist(0, 32), b('c2s'));
    expect(keys.sublist(32), b('s2c'));

    final session = SecureSession(id: sid, clientToServer: b('c2s'), serverToClient: b('s2c'), expiresAt: DateTime(2100));
    expect(utf8.decode(SecureCrypto.open(b('c2s'), b('reqIv'), b('reqCt'), SecureCrypto.requestAad('POST', '/api/auth/otp/request', 7, sid))),
        '{"phone":"251911000000"}');
    expect(session.openJson({'iv': v['resIv'], 'ct': v['resCt']}, 7), {'success': true, 'data': {'ok': 1}});
  });
}
